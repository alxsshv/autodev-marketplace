package com.autodev.platformservice.entity;

/**
 * Перечисление статусов верификации пользователя.
 * <p>
 * Отражает текущий этап прохождения процедуры верификации
 * учётной записи пользователя на платформе.
 * <p>
 * <b>Статусы:</b>
 * <ul>
 *   <li>{@link #NOT_VERIFIED} — пользователь не проходил верификацию
 *       (значение по умолчанию для новых пользователей в MVP).</li>
 *   <li>{@link #PENDING} — запрос на верификацию отправлен, ожидает проверки
 *       модератором или автоматической системой.</li>
 *   <li>{@link #VERIFIED} — пользователь успешно прошёл верификацию,
 *       все проверенные данные подтверждены.</li>
 *   <li>{@link #REJECTED} — запрос на верификацию отклонён
 *       (недостаточно информации, поддельные данные и т.д.).</li>
 * </ul>
 *
 * @see UserProfileEntity
 */
public enum VerificationStatus {

    /**
     * Пользователь не проходил верификацию.
     * <p>
     * Устанавливается по умолчанию для всех новых пользователей.
     * Основное ограничение для MVP.
     */
    NOT_VERIFIED,

    /**
     * Верификация в процессе.
     * <p>
     * Пользователь отправил данные на проверку (паспорт, документ и т.д.),
     * ожидает решения модератора или автоматической системы.
     */
    PENDING,

    /**
     * Верификация успешна пройдена.
     * <p>
     * Пользователь подтвердил свою личность. Получает расширенные
     * права на платформе (публикация товаров, участие в программах лояльности).
     */
    VERIFIED,

    /**
     * Верификация отклонена.
     * <p>
     * Предоставленные данные не прошли проверку (некорректные, поддельные,
     * неполные). Пользователю может быть разрешена повторная попытка.
     */
    REJECTED

}
