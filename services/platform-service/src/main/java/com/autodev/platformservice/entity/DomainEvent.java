package com.autodev.platformservice.entity;

/**
 * Интерфейс доменного события.
 * <p>
 * Реализации этого интерфейса представляют события, произошедшие в предметной области,
 * и используются для публикации в паттерн Outbox (Корзина исходящих сообщений).
 * События сериализуются и сохраняются в таблице outbox для последующей
 * асинхронной доставки потребителям через сообщения или веб-хуки.
 * <p>
 * Каждый реализующий интерфейс должен определить:
 * <ul>
 *   <li>Тип агрегата, к которому относится событие ({@link #getAggregateType()}),</li>
 *   <li>Имя топика для маршрутизации ({@link #getTopic()}),</li>
 *   <li>Уникальное имя типа события ({@link #getEventType()}).</li>
 * </ul>
 *
 * @see OutboxService
 * @see OutboxEntity
 * @see UserEvents
 */
public interface DomainEvent {

    /**
     * Возвращает тип агрегата, в контексте которого произошло событие.
     * <p>
     * Примеры: {@code "UserProfile"}, {@code "Order"}, {@code "Payment"}.
     * Используется для классификации и фильтрации событий.
     *
     * @return тип агрегата
     */
    String getAggregateType();

    /**
     * Возвращает имя топика (или канала) для маршрутизации события.
     * <p>
     * Используется при сохранении события в outbox и последующей
     * публикации в消息-брокер (Kafka, RabbitMQ и т.д.).
     *
     * @return имя топика
     */
    String getTopic();

    /**
     * Возвращает уникальное имя типа события.
     * <p>
     * Идентифицирует конкретное событие внутри агрегата.
     * Например: {@code "USER_REGISTERED"}, {@code "ORDER_CREATED"}.
     *
     * @return имя типа события
     */
    String getEventType();

}
